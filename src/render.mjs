/* ══════════════════════════════════════════════════════════════════════ */
/* block extensions                                                      */
/* ══════════════════════════════════════════════════════════════════════ */
/*
 * Five gwern-style block forms, all preprocessed BEFORE marked.
 *
 * Preprocessing rather than a marked extension is deliberate: each of these
 * brackets a region of ORDINARY Markdown, and doing it this way means the
 * body keeps being parsed normally instead of being handed to a tokenizer that
 * has to re-implement everything. The cost is that the delimiters must sit on
 * their own lines at column zero, which is exactly how they are written.
 *
 * Every one of them is emitted as a real HTML block with no script involved,
 * so all five survive JavaScript being switched off.
 */

const ADMONITIONS = {
  note: { name: "附注", glyph: "※" },
  aside: { name: "旁白", glyph: "◇" },
  warn: { name: "注意", glyph: "!" },
  quote: { name: "引文", glyph: "❝" },
  tip: { name: "提示", glyph: "✦" }
};

/**
 * Where one of these blocks ends.
 *
 * Every scanner below must use THIS pattern. They originally each spelled the
 * stop condition out themselves, and the copies drifted: two of them required a
 * space after the marker, so a bare `:::` did not stop the scanner, the
 * columns block was swallowed into the preceding admonition, and the whole
 * thing then failed to render as HTML at all. One constant, one meaning.
 */
/**
 * A line that begins — and therefore terminates — one of these blocks.
 *
 * Loosely anchored on purpose. `+++ 标题` is a block fold just as much as the
 * bracketed `+++[标题]` form, and `:::` stands alone. An earlier version
 * demanded a space after every marker in some scanners and not others, so a
 * bare `:::` failed to end the block above it and the two ran together. One
 * pattern, used by every scanner.
 */
const BLOCK_START = /^(?:!!!|\+\+\+|---|>>>|:::)(?:\s|$)/;
const isBlockStart = (line) => BLOCK_START.test(line) || /^#{1,6}\s/.test(line);

/** Gather the body of a block that starts at `i`. */
function gatherBody(lines, i) {
  const body = [];
  let j = i + 1;
  while (j < lines.length && !isBlockStart(lines[j])) {
    body.push(lines[j]);
    j++;
  }
  return { body, end: j - 1 };
}

/**
 * The `!` family: margin notes and admonitions.
 *
 * `!!!` and `!!!note` are the SAME first token, and they were originally handled
 * by two different passes in two different modules. The margin-note pass ran
 * first and quietly consumed every admonition, so admonitions never rendered —
 * they appeared as margin-note text, and nothing failed. They are scanned
 * together here so the split is visible and cannot regress.
 *
 *   !!! 文字          margin note — a skimmable summary of what follows
 *   !!! note 标题     admonition, with a type and an optional title
 */
function replaceBangs(src, notes) {
  const lines = src.split(/\r?\n/);
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const m = /^!!!\s*([a-zA-Z]+)?\s*(.*)$/.exec(lines[i]);
    if (!m) { out.push(lines[i]); continue; }

    const type = (m[1] || "").toLowerCase();
    const rest = (m[2] || "").trim();

    if (type && Object.prototype.hasOwnProperty.call(ADMONITIONS, type)) {
      const conf = ADMONITIONS[type];
      const { body, end } = gatherBody(lines, i);
      i = end;
      // blank lines around the div, or marked treats it as inline HTML inside
      // an enclosing paragraph and escapes the whole thing
      out.push("", `<div class="admon admon--${esc(type)}" role="note">`,
        `<p class="admon__title"><span class="admon__glyph" aria-hidden="true">${conf.glyph}</span>${esc(rest || conf.name)}</p>`,
        "",
        body.join("\n").trim(),
        "",
        "</div>", "");
      continue;
    }

    // anything else is a margin note; the type word, if any, is its text
    const text = (m[1] ? m[1] + " " : "") + rest;
    notes.push(text.trim());
    out.push("", `<div class="marginnote">${esc(text.trim())}</div>`, "");
  }
  return { text: out.join("\n"), notes };
}

/**
 * `+++[标题]` or `+++ 标题` — a foldable block.
 *
 * The bracketed form is the explicit one; the bare form takes the rest of the
 * line as its label. Both are BLOCK folds, because a fold with no label and no
 * body would be indistinguishable from a paragraph — if you want a one-line
 * fold, write the line.
 */
function replaceFolds(src) {
  const lines = src.split(/\r?\n/);
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const m = /^\+\+\+(?:\[([^\]]*)\]|)\s*(.*)$/.exec(lines[i]);
    if (!m) { out.push(lines[i]); continue; }

    const label = (m[1] !== undefined && m[1] !== null ? m[1] : (m[2] || "")).trim();
    const { body, end } = gatherBody(lines, i);
    i = end;

    out.push("", `<div class="fold">`,
      `<p class="fold__label"><span class="fold__text">${esc(label || "展开")}</span></p>`,
      "",
      body.join("\n").trim(),
      "",
      "</div>", "");
  }
  return out.join("\n");
}

/** `>>> 引文 — 出处` — an epigraph in the serif, indented, no container. */
function replaceEpigraphs(src) {
  return src.replace(
    /^>>>\s*([\s\S]*?)(?:\n\n|$)/gm,
    (_, block) => {
      const text = block.trim();
      // an em dash or "--" on the last line carries the attribution
      const m = /^(.*?)\s*(?:——|--|—)\s*(.+)$/s.exec(text);
      const body = m ? m[1].trim() : text;
      const by = m ? m[2].trim() : "";
      return `<div class="epigraph">\n\n> ${body.replace(/\n/g, "\n> ")}\n\n${
        by ? `<p class="epigraph__by">${esc(by)}</p>` : ""
      }\n\n</div>\n\n`;
    }
  );
}

/** `::: columns` … `:::` — a list that goes multi-column on wide screens. */
function replaceColumns(src) {
  return src.replace(
    /^:::[ \t]*columns[^\n]*\n([\s\S]*?)\n:::[ \t]*$/gm,
    (_, inner) => `\n\n<div class="columns">\n\n${inner.trim()}\n\n</div>\n\n`
  );
}

/**
 * Keyed citations: `[^key]` in the text, `[^key]: reference` at the end.
 *
 * gwern typesets references as subscripts rather than bracketed numbers because
 * they interrupt a sentence far less. The definition lines are collected here so
 * the page can emit one compact reference list; the in-text marker becomes a
 * superscript link to its entry.
 *
 * Note the deliberate distinction from `^[text]`, which is an inline footnote —
 * bracket-caret is a citation, caret-bracket is a note.
 */
function replaceCitations(src) {
  const defs = new Map();
  const order = [];

  // pull the definitions out first so they never render as paragraphs
  let text = src.replace(/^\[\^([^\]]+)\]:[ \t]*(.+)$/gm, (_, key, body) => {
    const k = key.trim();
    if (!defs.has(k)) { defs.set(k, body.trim()); order.push(k); }
    return "";
  });

  const used = [];
  text = text.replace(/\[\^([^\]]+)\]/g, (whole, key) => {
    const k = key.trim();
    if (!defs.has(k)) return whole;      // leave it alone; the build reports it
    let n = used.indexOf(k);
    if (n < 0) { used.push(k); n = used.length - 1; }
    return `<sup class="citeref"><a href="#cite-${esc(slugify(k) || n + 1)}">[${n + 1}]</a></sup>`;
  });

  const list = used.length
    ? `\n\n<section class="references" aria-labelledby="refs-h">\n\n` +
      `<h2 id="refs-h" class="references__h">参考</h2>\n\n` +
      `<ol class="references__list">\n` +
      used.map((k) => `<li id="cite-${esc(slugify(k) || "")}">${esc(defs.get(k))}</li>`).join("\n") +
      `\n</ol>\n\n</section>\n\n`
    : "";

  return { text: text + list, citations: used, missing: [...defs.keys()].filter((k) => !used.includes(k)) };
}

/* ══════════════════════════════════════════════════════════════════════ */
/* renderer                                                              */
/* ══════════════════════════════════════════════════════════════════════ */

function makeRenderer() {
  const renderer = new marked.Renderer();

  renderer.heading = function (token) {
    const text = this.parser.parseInline(token.tokens);
    // ids are assigned after all headings are known; see renderBody()
    return `<h${token.depth} data-h="${esc(plain(token.text || ""))}">${text}</h${token.depth}>\n`;
  };

  renderer.link = function (token) {
    const href = token.href || "";
    const external = /^https?:/i.test(href);
    const cls = external ? "ext" : "int";
    return `<a class="${cls}" href="${esc(href)}"${
      external ? ' target="_blank" rel="noopener noreferrer"' : ""
    }${token.title ? ` title="${esc(token.title)}"` : ""}>${this.parser.parseInline(token.tokens)}</a>`;
  };

  renderer.code = function (token) {
    // A plain-text site has no syntax highlighter, but indented verse must keep
    // its leading whitespace — so a code block is rendered as preserved text
    // rather than being silently reflowed.
    return `<pre class="verbatim">${esc(token.text)}</pre>\n`;
  };

  renderer.blockquote = function (token) {
    return `<blockquote>${this.parser.parse(token.tokens)}</blockquote>\n`;
  };

  renderer.hr = () => `<hr class="divider">\n`;

  return renderer;
}

