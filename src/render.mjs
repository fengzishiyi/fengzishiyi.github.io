/**
 * render.mjs — Markdown to HTML for this site.
 *
 * Three things here are site-specific rather than generic Markdown:
 *
 *  1. Stable heading anchors. A Chinese heading slugifies to nothing usable, so
 *     ids are positional (`sec-1`, `sec-2`) and never derived from the text —
 *     which also means editing a heading's wording cannot break a link
 *     someone saved.
 *  2. Section wrappers with a disclosure control, which is the whole of gwern's
 *     "semantic zoom" at the block level: a long piece can be read as headings
 *     alone, then expanded section by section.
 *  3. Footnote/sidenote and `{{ref:}}` handling, both preprocessed BEFORE
 *     marked so their bodies are themselves parsed as Markdown.
 */

import { marked } from "marked";
import { esc, plain, slugify } from "./lib.mjs";
import { replaceFootnotes, extractRefs, restoreRefs } from "./content.mjs";

/* ══════════════════════════════════════════════════════════════════════ */
/* headings & sections                                                   */
/* ══════════════════════════════════════════════════════════════════════ */

/** Collect every heading's level, text and positional id. */
function headingTokens(tokens, out = []) {
  for (const t of tokens || []) {
    if (t.type === "heading") {
      out.push({ level: t.depth, text: plain(marked.parseInline(t.text || "") || t.text || "") });
    } else if (t.tokens) {
      headingTokens(t.tokens, out);
    } else if (t.items) {
      for (const item of t.items) headingTokens(item.tokens, out);
    }
  }
  return out;
}

/** Wrap h2-and-below into <section> so each one can fold.
 *
 *  Regex surgery on rendered HTML rather than a custom tokenizer: the HTML at
 *  this point is entirely generated by this file, so the shape is known, and a
 *  regex keeps the section logic readable next to the folding CSS.
 */
/**
 * Wrap h2-and-below into <section> so each one can fold, and drop in the
 * backlinks that point at THAT section.
 *
 * Section-level backlinks are the reason anchors are positional (`sec-1`,
 * `sec-2`): a link to `{{ref:x|#sec-3}}` can be resolved to the section it lands
 * in, so a reader finishing a section immediately sees who else cites that part
 * rather than only which pages cite the whole piece. gwern calls this the
 * in-context backlink, and most backlink systems cannot do it.
 */
export function buildSections(html, headings, backlinksBySection = new Map()) {
  const byId = new Map(headings.map((h) => [h.id, h]));

  const backlinkBlock = (id) => {
    const list = backlinksBySection.get(id);
    if (!list || !list.length) return "";
    return `<div class="sectionback">\n<p class="sectionback__h">本节被这些地方引用</p>\n<ul class="sectionback__list">\n${
      list.map((b) => `<li><a href="${esc(b.fromUrl)}#${esc(id)}">${esc(b.fromTitle)}</a>${
        b.context ? `<span class="sectionback__ctx">${esc(b.context)}</span>` : ""
      }</li>`).join("\n")
    }\n</ul>\n</div>\n`;
  };

  // The rendered HTML is entirely ours, so splitting on headings is safe and
  // keeps the section boundaries and the backlink placement in one pass.
  //
  // Sections NEST: an h3 belongs to the h2 above it, so folding that h2 hides
  // the whole section, subsections included. Emitting them as siblings was the
  // first version, and it meant folding a section left its subsections on
  // screen — which reads as a broken fold, not as a design choice.
  const parts = html.split(/(?=<h[23] id=")/);
  let out = "";
  const open = [];   // ids of the sections currently open, outermost first

  const closeTo = (level) => {
    while (open.length && open[open.length - 1].level >= level) {
      const s = open.pop();
      out += backlinkBlock(s.id) + "</section>";
    }
  };

  for (const part of parts) {
    const m = /^<h([23]) id="([^"]+)"/.exec(part);
    if (!m) {
      out += part;
      continue;
    }
    const level = Number(m[1]);
    const id = m[2];
    closeTo(level);

    const h = byId.get(id);
    const title = h ? h.text : "";
    open.push({ id, level });
    out += `<section class="${level === 2 ? "sec" : "subsec"}" aria-labelledby="${id}">` +
      part.replace(
        new RegExp(`^<h${level} id="${id}"([^>]*)>`),
        `<h${level} id="${id}"$1><a class="anchor" href="#${id}" aria-label="本节链接：${esc(title)}">#</a>`
      );
  }
  closeTo(2);

  return out;
}

