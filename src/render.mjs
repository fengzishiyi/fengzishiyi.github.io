/** Plain text of a rendered body, for the search index. Notes and refs are
 *  included: a note often carries the detail someone is searching for. */
export const searchText = (html) => plain(html).slice(0, 20000);

/** A short excerpt around the first occurrence of `needle`, for previews. */
export function excerpt(html, needle, width = 260) {
  const text = plain(html);
  if (!needle) return text.slice(0, width) + (text.length > width ? "…" : "");
  const i = text.toLowerCase().indexOf(String(needle).toLowerCase());
  if (i < 0) return text.slice(0, width) + (text.length > width ? "…" : "");
  const start = Math.max(0, i - 60);
  return (start > 0 ? "…" : "") + text.slice(start, start + width) + "…";
}
