/**
 * Render one article body.
 *
 * Order matters: footnotes and margin notes are expanded first (their bodies
 * are Markdown), then refs are pulled out as placeholders so marked never sees
 * a half-formed link, then Markdown runs, then refs are restored and headings
 * get their final ids.
 */
export function renderBody(article, { resolve, sectionBacklinks = new Map() } = {}) {
  const notes = [];
  let src = article.body;

  // Block extensions run before refs are pulled out, so a `{{ref:}}` inside an
  // admonition or a fold is still recognised as a link.
  src = replaceColumns(src);
  const bangs = replaceBangs(src, []);
  src = bangs.text;
  src = replaceFolds(src);
  src = replaceEpigraphs(src);

  // Inline footnotes come after the block scanners: their bodies are Markdown
  // and may contain markers, and running them last keeps the two `!` forms from
  // being confused for each other.
  src = replaceFootnotes(src, notes);

  const cites = replaceCitations(src);
  src = cites.text;

  const { text, links } = extractRefs(src, article.slug);

  let html = marked.parse(text, {
    renderer: makeRenderer(),
    gfm: true,
    breaks: false
  });

  html = restoreRefs(html, links, resolve);
  html = linkIcons(html);

  // position the headings now that the document is whole
  const collected = headingTokens(marked.lexer(text));
  const headings = [];
  let n = 0;
  html = html.replace(/<h([1-6]) data-h="[^"]*">/g, (_, level) => {
    const src2 = collected[n];
    n += 1;
    const depth = Number(level);
    const id = `sec-${n}`;
    headings.push({ level: depth, id, text: src2 ? src2.text : "" });
    return `<h${depth} id="${id}">`;
  });

  const sectioned = buildSections(html, headings, sectionBacklinks);

  return {
    html: sectioned,
    headings: headings.filter((h) => h.level === 2),
    allHeadings: headings,
    notes,
    citations: cites.citations,
    unusedCitations: cites.missing,
    links: links.map((l) => l.target)
  };
}

/**
 * Tag external links by what they point at.
 *
 * gwern.net does this with several hundred hand-tuned regexes and a folder of
 * icons; this is the abbreviated version — four categories, drawn as an inline
 * SVG so nothing is requested, and applied by attribute selector in CSS rather
 * than by rewriting every link.
 *
 * The icon is `aria-hidden` and the information is also carried in the link's
 * `title`, so it is decoration for sighted readers rather than the only signal.
 */
export function linkIcons(html) {
  return html.replace(/<a class="ext"([^>]*)>/g, (whole, attrs) => {
    const href = /href="([^"]*)"/.exec(attrs);
    if (!href) return whole;
    const url = href[1];
    let kind = "web";
    if (/\.pdf(?:$|\?)/i.test(url)) kind = "pdf";
    else if (/^https?:\/\/(?:en\.)?wikipedia\.org\//i.test(url)) kind = "wikipedia";
    else if (/^https?:\/\/(?:dx\.)?doi\.org\//i.test(url)) kind = "doi";
    else if (/^https?:\/\/(?:arxiv\.org|www\.arxiv\.org)\//i.test(url)) kind = "arxiv";
    return `<a class="ext ext--${kind}"${attrs}>`;
  });
}

